//! Sticky notes per terminal member and per workspace (ADR-012).

use super::*;
use crate::notes::{
    clean_text, move_member_note_to_project, set_note, Trash, TrashEntry, TrashedMember,
    WorkspaceNotes, NOTES_FORMAT, NOTES_SCHEMA, TRASH_FORMAT,
};

const TRASH_NAME: &str = "trash";

/// What the UI needs for one workspace.
#[derive(Debug, Clone, Serialize)]
pub struct NotesView {
    pub project: String,
    pub project_updated_at: u64,
    /// member id -> text (members without a note are absent)
    pub members: std::collections::BTreeMap<String, String>,
    /// Workspaces deleted recently whose notes can still be restored.
    pub trash: Vec<TrashSummary>,
}

#[derive(Debug, Clone, Serialize)]
pub struct TrashSummary {
    pub id: String,
    pub workspace_name: String,
    pub deleted_at: u64,
    pub notes: usize,
}

fn store_name(workspace_id: &str) -> Result<String, String> {
    // Workspace ids are generated by the core (`ws_<hex>`); anything else is
    // refused so a name can never point outside the notes folder.
    if workspace_id.is_empty()
        || workspace_id.len() > 64
        || !workspace_id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    {
        return Err("invalid workspace id".into());
    }
    Ok(format!("notes-{workspace_id}"))
}

impl Core {
    /// Notes of a workspace, loaded from disk on first use.
    pub(super) fn workspace_notes(&self, workspace_id: &str) -> Result<WorkspaceNotes, String> {
        let name = store_name(workspace_id)?;
        let mut cache = self.notes.locked();
        if let Some(n) = cache.get(workspace_id) {
            return Ok(n.clone());
        }
        let (loaded, report) =
            self.notes_store
                .load::<WorkspaceNotes>(&name, NOTES_FORMAT, NOTES_SCHEMA, &[]);
        if report.recovered {
            crate::logging::warn(
                "notes",
                &format!(
                    "notes of {workspace_id} restored from an earlier save: {}",
                    report.problems.join("; ")
                ),
            );
        }
        let notes = loaded.unwrap_or_default();
        cache.insert(workspace_id.to_string(), notes.clone());
        Ok(notes)
    }

    /// Save first, then update the cache: a failed save changes nothing.
    fn store_notes(&self, workspace_id: &str, notes: WorkspaceNotes) -> Result<(), String> {
        let name = store_name(workspace_id)?;
        if notes.is_empty() {
            self.notes_store.remove(&name);
        } else {
            self.notes_store
                .save(&name, NOTES_FORMAT, NOTES_SCHEMA, &notes)?;
        }
        self.notes.locked().insert(workspace_id.to_string(), notes);
        Ok(())
    }

    fn trash(&self) -> Trash {
        let (trash, _) =
            self.notes_store
                .load::<Trash>(TRASH_NAME, TRASH_FORMAT, NOTES_SCHEMA, &[]);
        let mut trash = trash.unwrap_or_default();
        trash.prune(now_ms());
        trash
    }

    pub fn notes_view(&self, workspace_id: &str) -> Result<NotesView, String> {
        check_id(workspace_id)?;
        if self
            .data
            .locked()
            .state
            .workspaces
            .iter()
            .all(|w| w.id != workspace_id)
        {
            return Err("workspace not found".into());
        }
        let notes = self.workspace_notes(workspace_id)?;
        Ok(NotesView {
            project: notes.project.text.clone(),
            project_updated_at: notes.project.updated_at,
            members: notes
                .members
                .iter()
                .map(|(id, n)| (id.clone(), n.text.clone()))
                .collect(),
            trash: self
                .trash()
                .entries
                .iter()
                .map(|e| TrashSummary {
                    id: e.id.clone(),
                    workspace_name: e.workspace_name.clone(),
                    deleted_at: e.deleted_at,
                    notes: usize::from(!e.project.is_empty()) + e.members.len(),
                })
                .collect(),
        })
    }

    /// Save one note. `member_id` None = the workspace's project note.
    pub fn save_note(
        &self,
        workspace_id: &str,
        member_id: Option<&str>,
        text: &str,
    ) -> Result<u64, String> {
        check_id(workspace_id)?;
        let text = clean_text(text)?;
        {
            let data = self.data.locked();
            let w = data
                .state
                .workspaces
                .iter()
                .find(|w| w.id == workspace_id)
                .ok_or("workspace not found")?;
            if let Some(m) = member_id {
                check_id(m)?;
                if w.member(m).is_none() {
                    return Err("member not found".into());
                }
            }
        }
        let _guard = self.notes_write.locked();
        let mut notes = self.workspace_notes(workspace_id)?;
        let at = set_note(&mut notes, member_id, text, now_ms())?;
        self.store_notes(workspace_id, notes)?;
        Ok(at)
    }

    /// Called after a member was removed: its note joins the project note.
    pub(super) fn keep_removed_member_note(
        &self,
        workspace_id: &str,
        member_id: &str,
        title: &str,
    ) {
        let _guard = self.notes_write.locked();
        let Ok(mut notes) = self.workspace_notes(workspace_id) else {
            return;
        };
        if move_member_note_to_project(&mut notes, member_id, title, now_ms()) {
            if let Err(error) = self.store_notes(workspace_id, notes) {
                crate::logging::error("notes", &format!("could not keep a removed note: {error}"));
            }
        }
    }

    /// Called before a workspace is deleted: its notes go to the bounded
    /// "recently deleted" list. Returns Err if that could not be saved, so
    /// the caller can refuse to delete rather than lose text.
    pub(super) fn trash_workspace_notes(
        &self,
        workspace_id: &str,
        workspace_name: &str,
        titles: &HashMap<String, String>,
    ) -> Result<(), String> {
        let _guard = self.notes_write.locked();
        let notes = self.workspace_notes(workspace_id)?;
        if notes.is_empty() {
            self.notes_store.remove(&store_name(workspace_id)?);
            self.notes.locked().remove(workspace_id);
            return Ok(());
        }
        let mut trash = self.trash();
        trash.entries.insert(
            0,
            TrashEntry {
                id: new_id("trash"),
                workspace_name: workspace_name.to_string(),
                deleted_at: now_ms(),
                project: notes.project.text.clone(),
                members: notes
                    .members
                    .iter()
                    .filter(|(_, n)| !n.text.is_empty())
                    .map(|(id, n)| TrashedMember {
                        title: titles.get(id).cloned().unwrap_or_else(|| id.clone()),
                        text: n.text.clone(),
                    })
                    .collect(),
            },
        );
        trash.prune(now_ms());
        self.notes_store
            .save(TRASH_NAME, TRASH_FORMAT, NOTES_SCHEMA, &trash)?;
        self.notes_store.remove(&store_name(workspace_id)?);
        self.notes.locked().remove(workspace_id);
        Ok(())
    }

    /// Append a deleted workspace's notes to a project note and drop them
    /// from the list.
    pub fn restore_trashed_notes(
        &self,
        trash_id: &str,
        into_workspace: &str,
    ) -> Result<(), String> {
        check_id(trash_id)?;
        check_id(into_workspace)?;
        let _guard = self.notes_write.locked();
        let mut trash = self.trash();
        let index = trash
            .entries
            .iter()
            .position(|e| e.id == trash_id)
            .ok_or("those notes are no longer available")?;
        let entry = trash.entries[index].clone();
        let mut notes = self.workspace_notes(into_workspace)?;
        let mut text = notes.project.text.clone();
        let mut block = format!(
            "— Notes of the deleted workspace “{}” —\n",
            entry.workspace_name
        );
        if !entry.project.is_empty() {
            block.push_str(&entry.project);
            block.push('\n');
        }
        for m in &entry.members {
            block.push_str(&format!("\n[{}]\n{}\n", m.title, m.text));
        }
        if !text.is_empty() {
            if !text.ends_with('\n') {
                text.push('\n');
            }
            text.push('\n');
        }
        text.push_str(block.trim_end());
        let text = clean_text(&text)?;
        set_note(&mut notes, None, text, now_ms())?;
        self.store_notes(into_workspace, notes)?;
        trash.entries.remove(index);
        self.notes_store
            .save(TRASH_NAME, TRASH_FORMAT, NOTES_SCHEMA, &trash)?;
        Ok(())
    }
}
